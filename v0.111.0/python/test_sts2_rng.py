def test_random_monster_ai_confirmed_in_game():
    """RANDOM-AI VALIDATION (2026-07-09): Sean replayed ZPJHU3WSH2 fight 4
    (3 Two-Tailed Rats) and recorded intents turns 1-4. Observed exactly:
      t1 atk9|atk7|debuff (k=0), t2 debuff|atk9|atk9, t3 atk7|atk7|summon,
      t4 (new rat leftmost) atk7|atk9|debuff|atk9.
    Fit: MonsterAi counter 0 entering fight 4; starter IS logged (SL=Y);
    rolls in slot order L->R; the summoned rat's spawn-time roll (draw 7)
    is its next intent with NO re-roll; 10 draws total through turn 4."""
    from monster_ai import Rat
    from sts2_rng import Rng, RunRngSet

    rng = Rng(RunRngSet("ZPJHU3WSH2")["MonsterAi"].seed)
    rats = [Rat(i) for i in range(3)]          # k=0
    for r in rats:
        r.intent = r.starter
        r.log.append(r.starter)                # starter logged (confirmed)
    observed = [
        ["SCRATCH", "DISEASE_BITE", "SCREECH"],            # turn 1
        ["SCREECH", "SCRATCH", "SCRATCH"],                 # turn 2
        ["DISEASE_BITE", "DISEASE_BITE", "CALL_FOR_BACKUP"],  # turn 3
    ]
    assert [r.intent for r in rats] == observed[0]
    backup = 0
    for turn in (2, 3):
        for r in rats:
            if turn > 2:
                r.log.append(r.intent)
            if r.intent != "CALL_FOR_BACKUP":
                r.turns_until_summonable -= 1
        for r in rats:
            teammate = any(o is not r and o.intent == "CALL_FOR_BACKUP"
                           for o in rats)
            can = r.turns_until_summonable <= 0 and backup < 3 and not teammate
            r.intent = r.roll(rng, can)
        assert [r.intent for r in rats] == observed[turn - 1], f"turn {turn}"
    # turn-3 execution: two bites + the summon
    for r in rats:
        r.log.append(r.intent)
        if r.intent != "CALL_FOR_BACKUP":
            r.turns_until_summonable -= 1
        else:
            backup += 1
    new = Rat(-1)
    new.intent = new.roll(rng, can_summon=False)   # spawn roll = t4 intent
    new.log.append(new.intent)
    for r in rats:                                 # originals roll; slots full
        r.intent = r.roll(rng, can_summon=False)
    assert [new.intent] + [r.intent for r in rats] == \
        ["DISEASE_BITE", "SCRATCH", "SCREECH", "SCRATCH"]  # observed turn 4
    assert rng.counter == 10


