def test_counter_and_fast_forward_equivalence():
    # A fresh Rng fast-forwarded to counter N must produce the same draws
    # as an Rng that made N calls (any mix of draw methods).
    a = Rng(123456)
    a.next_int(100)
    a.next_bool()
    a.next_double()
    a.next_float(1.0)
    a.next_unsigned_int(5, 50)
    assert a.counter == 5

    b = Rng(123456, counter=5)
    assert b.counter == 5
    assert [a.next_int(1000) for _ in range(8)] == \
        [b.next_int(1000) for _ in range(8)]


def test_shuffle_semantics():
    # n-1 counter ticks; exact permutation pinned against a manual
    # replay of the IL algorithm (top-down Fisher-Yates, j = next_int(i+1)).
    rng = Rng(42)
    items = list(range(10))
    rng.shuffle(items)
    assert rng.counter == 9

    replay = Rng(42)
    manual = list(range(10))
    for i in range(9, 0, -1):
        j = replay.next_int(i + 1)
        manual[j], manual[i] = manual[i], manual[j]
    assert items == manual
    assert sorted(items) == list(range(10))


def test_stream_seed_derivation():
    # run stream seed = hash(seed_string) + hash(snake_case(name)), int32 wrap
    seed_string = "ZPJHU3WSH2"
    rs = RunRngSet(seed_string)
    assert rs.seed == deterministic_hash_code(seed_string) == 1584024330
    for name in RUN_RNG_STREAMS:
        expected = rs.seed + deterministic_hash_code(snake_case(name))
        expected = ((expected & 0xFFFFFFFF) ^ 0x80000000) - 0x80000000
        assert rs[name].seed == expected, name

    # player set: + slot index before per-stream hash
    p0 = PlayerRngSet(seed_string, 0)
    p1 = PlayerRngSet(seed_string, 1)
    assert p1.seed == p0.seed + 1
    assert p0["Rewards"].seed != p1["Rewards"].seed


