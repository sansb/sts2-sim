_HERE = Path(__file__).resolve().parent
TABLES_PATH = _HERE / "mcr_tables.json"

# mcr_tables.json tracks the CURRENT game version (regenerate it after every
# version bump: tools/build_mcr_tables.py). Older builds whose replays we
# still decode get a frozen copy, because their sts2.dll may be gone — Steam
# deletes old builds, and v0.108.0's is (see dll-archive/README.md), so
# mcr_tables_v0.108.0.json can never be rebuilt and must not be regenerated.
# v0.109.0 replays decode with the v0.109.1 tables: the #625 impact check
# found the two builds CIL-identical, so their net-id registries are equal.
TABLES_BY_VERSION = {
    "v0.108.0": _HERE / "mcr_tables_v0.108.0.json",
    "v0.109.0": _HERE / "mcr_tables_v0.109.1.json",
    "v0.109.1": _HERE / "mcr_tables_v0.109.1.json",
    "v0.110.1": _HERE / "mcr_tables_v0.110.1.json",
}

_TABLE_CACHE = {}


def load_tables(path):
    path = Path(path)
    if path not in _TABLE_CACHE:
        _TABLE_CACHE[path] = json.loads(path.read_text())
    return _TABLE_CACHE[path]


def tables_for_version(version):
    """The net-id tables for the game build that wrote a replay."""
    return load_tables(TABLES_BY_VERSION.get(version, TABLES_PATH))


