"""Decoder for Slay the Spire 2 combat replay files (replays/latest.mcr).

SHELVED for the product (July 2026): the game keeps only latest.mcr,
overwritten every combat, so user-facing capture requires a resident
watcher app — install friction we decided against (issue #66; #61/#28
closed wontfix). In active DEV-SIDE use since #118 (2026-07-14) as the
input-log half of the live-play validation harness (tools/mcr_watch.py,
tools/mcr_validate.py). MCR_FORMAT.md "Counter caveat" is WITHDRAWN as of
#639: the snapshot's rng dict always carried every stream cumulatively —
the old "it only holds UpFront" reading was an evaluation-order bug in this
file. v0.109 additionally carries each stream's xoshiro state and a full
combat-state snapshot per action in the checksum section.

The game writes one CombatReplay per combat via a bit-packing serializer
(MegaCrit.Sts2.Core.Multiplayer.Serialization.PacketWriter): values are
written LSB-first into a little-endian bitstream. The schema below is a
direct transcription of the IL of each type's Serialize/Deserialize in
sts2.dll — v0.108.0 originally, re-derived on v0.109.1 in #639 (see
MCR_FORMAT.md and tools/dump_serializer.py). Where the two builds differ
the decoder branches on the header's version string. v0.110.1 carries the
v0.109.1 schema unchanged (#807): only the net-id tables moved.

Model ids (cards, relics, encounters, ...) are stored as compact integer
"net ids"; the lookup tables live in mcr_tables.json, generated by
tools/build_mcr_tables.py from the installed sts2.dll. The tables'
XxHash32 must match the file's modelIdHash header field — decode() checks.
Net ids are assigned per game build, so the tables are version-specific:
decode() reads the version string out of the header and picks the matching
table file (see TABLES_BY_VERSION).

Usage:
    python3 mcr_parser.py [path/to/latest.mcr] [--json out.json]
"""
